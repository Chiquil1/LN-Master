import type { SiteStructure, Selectors, ExtractorOptions } from '../types';
import { generateMadaraBaseClass } from './baseClassGenerator';

export function generatePlugin(
  structure: SiteStructure,
  selectors: Selectors,
  options: ExtractorOptions,
): { pluginCode: string; baseClassCode?: string } {
  const { siteType, siteName: _siteName, baseUrl: _baseUrl } = structure;

  let pluginCode: string;
  let baseClassCode: string | undefined;

  switch (siteType) {
    case 'madara-cms':
      baseClassCode = generateMadaraBaseClass(structure, selectors);
      pluginCode = generateMadaraPlugin(structure, selectors, options);
      break;
    case 'lightnovelwp-cms':
      pluginCode = generateLightnovelwpPlugin(structure, selectors, options);
      break;
    case 'api-json':
      pluginCode = generateApiPlugin(structure, selectors, options);
      break;
    case 'novelyra-custom':
      pluginCode = generateNovelyraPlugin(structure, selectors, options);
      break;
    default:
      pluginCode = generateGenericPlugin(structure, selectors, options);
  }

  return { pluginCode, baseClassCode };
}

