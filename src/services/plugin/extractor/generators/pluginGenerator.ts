function formatSelectorArray(arr: string[]): string {
  return (arr || []).map(s => `'${escapeString(s)}'`).join(', ');
}

function escapeString(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
}

function capitalizeFirst(str: string): string {
  return (
    str.charAt(0).toUpperCase() +
    str.slice(1).replace(/[-_](.)/g, (_, c) => c.toUpperCase())
  );
}

function _getSel(selectors: Selectors, key: keyof Selectors): string {
  const arr = selectors[key];
  return arr && arr.length > 0 ? arr[0] : '';
}
